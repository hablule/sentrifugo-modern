    public function getPeriods($date,$where)
    {
        $config = array(
            'name'=>'main_period',
            'primary'=>'period_id'
        );
        if ($where!='') {
            $where = ' AND '.$where;
        }
        $table = new Zend_Db_Table($config);    
        $period = $table->select()
                        ->setIntegrityCheck(false)
                        ->from(array('p'=>$config['name']),array('p.period_id','p.end_date','P.start_date'))
                        ->joinInner(array('pc'=>'main_periodcontrol'),'pc.period_id=p.period_id','pc.isautogenerated')
                        ->where("p.isactive = 'Y' AND pc.control_type = 'REMUNERATION' AND '".$date."' BETWEEN p.start_date AND p.end_date".$where);
             //die($period);
       return $table->fetchAll($period)->toArray();

    }

    public function getlastdocno()
    {
        $config = array(
            'name'=>'main_payroll',
            'primary'=>'id'
        );
        $table = new Zend_Db_Table($config);
        $lastid = $table->getDefaultAdapter()->query('SELECT MAX(id) as lastid, docment_no from main_payroll');
        $lastid = $table->select()
                        ->setIntegrityCheck(false)
                        ->from('main_payroll',array('MAX(id) as lastid','docment_no as docno'))
                        ->where('id = (SELECT MAX(id) FROM main_payroll)');
           
        return $table->fetchRow($lastid)->toArray();
        
    }
