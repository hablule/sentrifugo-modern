    /**
     * 
     * Responsible for calculating net salary of an employee
     * @param int $empid 
     * @param int $payrolllineid  payroll line id
     * @param date $date   
     * 
     * @return void
     * 
     * 
     */

    public function payroll_detail($empid, $payrolllineid, $date)
    {

        $cronmodel = new Payroll_Model_cronjob();
        $addundummodel = new Default_Model_Addundum();
        $otmodel = new Schedule_Model_Overtime();
        $missmodel = new Default_Model_Missedhoursapprove();
        $addundum = $cronmodel->getaddundum($empid);
        $ot = $cronmodel->getovertime($empid);
        $missed = $cronmodel->getmisshours($empid);
        $linelist = $cronmodel->lineautoinc('main_payroll_detail', 'line', 'id');
        $line = $linelist['line'] + 1;
        $maxdata = max(array(count($addundum), count($ot), count($missed))); //select the max count from the given array
        Zend_Debug::dump($maxdata, 'max');
        $total_amount = 0;
        $payline = $cronmodel->getpayline($payrolllineid);
        $netsalary = $payline['basicsalary'];

        for ($i = 0; $i < $maxdata; $i++) {
            Zend_Debug::dump($addundum[$i]['amount_approved'], 'aa');
            Zend_Debug::dump($ot[$i]['approved_amount'], 'ot');
            Zend_Debug::dump($missed[$i]['approved_amount'], 'miss');

            $addundumstatus = $this->checkaddundum($addundum[$i]);

            if ($addundumstatus !== 'null') {
                if ($addundumstatus == 'perk') {
                    $total_amount = $addundum[$i]['amount_approved'] + $ot[$i]['approved_amount'] - $missed[$i]['approved_amount'];
                } else {

                    $total_amount =  $ot[$i]['approved_amount'] - $addundum[$i]['amount_approved'] - $missed[$i]['approved_amount'];
                    //die($total_amount);
                }
            } else {
                $total_amount = $ot[$i]['approved_amount'] - $missed[$i]['approved_amount'];
            }


            $data = array(
                'pay_line_id' => $payrolllineid,
                'line' => $line,
                'addundm_id' => $addundum[$i]['addundum_id'],
                'ot_approval_id' => $ot[$i]['OT_approval_id'],
                'absent_approval_id' => $missed[$i]['missed_hours_id'],
                'amount' => $total_amount
            );
            $line = $line + 1;
            if ($addundum[$i]['addundum_id'] != null) {
                $addata = array(
                    'paydate' => $date,
                    'processed' => 'Y'
                );
                $addundummodel->saveorupdate($addata, 'addundum_id = ' . $addundum[$i]['addundum_id']);
            }
            if ($ot[$i]['OT_approval_id'] != null) {
                $otdata = array(
                    'processed' => 'Y'
                );
                $otmodel->saveORupdateApproval($otdata, 'OT_approval_id = ' . $ot[$i]['OT_approval_id']);
            }
            if ($missed[$i]['missed_hours_id'] != null) {
                $missedata = array(
                    'processed' => 'Y'
                );
                $missmodel->editmissedhours($missedata, 'missed_hours_id = ' . $missed[$i]['missed_hours_id']);
            }
            Zend_Debug::dump($data);
            $netsalary = $netsalary + $total_amount;
            $cronmodel->saveorupdatepdetail($data, '');
        }
        $data = array(
            'netpay' => $netsalary
        );
        Zend_Debug::dump($data, 'netpay');

        $cronmodel->saveorupdatepline($data, 'id = ' . $payrolllineid);
        //Zend_Debug::dump($total_amount,'mikais');
    }








    /**
     * Checks the given addundum is a perk or load
     * @param array $addundum 
     * @return string
     */
    public function checkaddundum($addundum)
    {

        if ($addundum['perk_id'] != null) {
            return 'perk';
        } elseif ($addundum['load_id'] != null) {
            return 'load';
        } else {
            return 'null';
        }
    }




