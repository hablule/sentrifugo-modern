    /**
     * entrypoint to auto generate the payroll
     * @param date $date
     * @return void
     */
    public function addpayroll($date)
    {
        $payrollmodel = new Default_Model_payroll();
        $cronmodel = new Payroll_Model_cronjob();
        $periods = $this->getPeriod($date, 'pc.isautogenerated = "Y"');
        foreach ($periods as $key => $period) {
            if ($this->doesperiodexist($period['period_id'])) {
                continue;
            }   
        $lastinserted = $cronmodel->getlastdocno();
        if ($lastinserted['lastid'] == null) {
            $docno = 1;
        } else {
            $docno = $lastinserted['docno'] + 1;
        }
        $data = array(
            'docment_no' => $docno,
            'period_id' => $period['period_id'],
            'paydate' => $period['end_date'],
            'approved' => sapp_Global::change_date(date('Y-M-d'), 'database'),
            'approvedby' => 0,
            'autogenrerated' => 'Y'
        );

        $lastinsertedid = $payrollmodel->saveorupdate($data, '');
        //  die($period['start_date']." :startdate-end date: ".$period['end_date']);
        $this->payroll_line($data['paydate'], $lastinsertedid, $period['start_date'], $period['end_date']);
        Zend_Debug::dump($data);
    }
    }
    public function getPaydate($date)
