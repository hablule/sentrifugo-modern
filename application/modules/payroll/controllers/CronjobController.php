        $cronmodel = new Payroll_Model_cronjob();
        $periodstatus = $cronmodel->getPeriods($date, '');
        if ($periodstatus['isautogenerated'] == 'Y') {
            if ($periodstatus['end_date'] == $date) {
                return true;    # code...
            }
            return false;
        } else {
            return false;
        }
    }

