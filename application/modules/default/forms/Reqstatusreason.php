<?php

/**
 * Requisition Status Reason Form
 *
 * Manages the vocabulary of reasons for pipeline status transitions.
 * Complies with SSOT v6.7.7 (Zend_Form, Strict Regex, Balanced AJAX Submission).
 *
 * @category   Application
 * @package    Default
 * @subpackage Forms
