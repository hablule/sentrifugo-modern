<?php


class Default_Model_periodcontroltype extends Zend_Db_Table
{
    protected $_name = 'main_periodcontrol';
    protected $_primary = 'periodcontrol_id';

    public function getPeriodControlType($sort,$by,$pageNo,$perPage,$searchQuery)
    {
        $where = "1";

        if($searchQuery)
            $where .= " AND ".$searchQuery;
        
      	
        $periodcontroltype = $this->select()
                                  ->setIntegrityCheck(false)
                                  ->from(['pc' => 'main_periodcontrol'],['periodcontrol_id','control_type','if(isautogenerated="Y","Yes","No") AS isautogenerated'])
                                  ->joinLeft(['p' => 'main_period'], "p.period_id =pc.period_id ", ['period' => 'p.name'])
                                  ->order("$by $sort")
                                  ->where($where)
                                  ->limitPage($pageNo,$perPage);
        return $periodcontroltype;
    }


    public function getGrid($sort,$by,$perPage,$pageNo,$searchData,$call,$dashboardcall,$a='',$b='',$c='',$d='')
    {
        $searchQuery = '';
        $searchArray = [];
        if($searchData != '' && $searchData!='undefined')
			{
				$searchValues = json_decode($searchData);
				foreach($searchValues as $key => $val)
				{
					$searchQuery .= " ".$key." like '%".$val."%' AND ";
					$searchArray[$key] = $val;
				}
				$searchQuery = rtrim($searchQuery," AND");					
			}
            $objName = 'periodcontroltype';
            $tableFields = ['action'=>'Action','period'=>'Period','control_type' => 'Control Type','isautogenerated' => 'Auto Generate'];
            
            $tablecontent = $this->getPeriodControlType($sort, $by, $pageNo, $perPage,$searchQuery);
            $dataTmp = [
                'sort' => $sort,
                'by' => $by,
                'pageNo' => $pageNo,
                'perPage' => $perPage,				
                'tablecontent' => $tablecontent,
                'objectname' => $objName,
                'extra' => [],
                'tableheader' => $tableFields,
                'jsGridFnName' => 'getAjaxgridData',
                'jsFillFnName' => '',
                'searchArray' => $searchArray,
                'call'=>$call,
                'add'=>'add',

                'dashboardcall'=>$dashboardcall,
                'search_filters'=>[
                    'isautogenerated'=>[
                        'type'=>'select',
                        'filter_data'=>[''=>'All','Y'=>'Yes','N'=>'No']
                    ],
                    'control_type'=>[
                        'type'=>'select',
                        'filter_data'=>[''=>'All','REMUNERATION'=>'REMUNERATION','APPRAISAL'=>'APPRAISAL']
                    ]
                ]
            ];
            return $dataTmp;	
    }

    public function getPeriod()
    {
        $config = [
            'name'=>'main_period',
            'id'=>'period_id'
        ];
        $table = new Zend_Db_Table($config);
        $period=$table->select()
              ->setIntegrityCheck(false)
              ->where("isactive = 'Y'");
        
        return $table->fetchAll($period)->toArray();

    }
    
    public function savaorupdateperiodcontrol($data,$where)
    {
        if ($where!='') {
            $this->update($data,$where);
            return 'update';
        }
        else
        {
            try {
                $this->insert($data);
                return $this->getAdapter()->lastInsertId();
            } catch (\Throwable $th) {
              Zend_Debug::dump($th->getMessage()) ;
            }
            
        }
    }

    public function getPeriodControlTypeByid($id)
    {
        $periods = $this->select()
                        ->setIntegrityCheck(false)
                        ->where('periodcontrol_id = '.$id);
        //die($periods);
        return $this->fetchRow($periods)->toArray();
    }
    public function checkpc($id,$controltype)
    {
        $pc = $this->select()
                    ->setIntegrityCheck(false)
                    ->where('period_id = '.$id.' AND control_type = "'.$controltype.'"');
        return $this->fetchAll($pc)->toArray();
        
    }
} 


