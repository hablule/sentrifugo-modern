    public function checkpcpatternAction()
    {
        $this->_helper->viewRenderer->setNoRender(true);
        $percontypemodel = new Default_Model_periodcontroltype();
        $form = new Default_Form_periodcontroltype();

        $pc = $percontypemodel->checkpc($this->_request->getParam('period'), $this->_request->getParam('controltype'));
        if (count($pc)>0) {
            $form->period->setErrors(array('invalid form'));
            return $this->_helper->json(array('result'=>'true'));
        }
        else{
            return $this->_helper->json(array('result'=>'false'));
        }

    }
