    public function init()
    {
        $this->_options = $this->getInvokeArg('bootstrap')->getOptions();
        require_once 'application/modules/default/library/utilClasses/Util.php';
        require_once 'application/modules/default/library/utilClasses/addformcomponent.php';
    }

    public function indexAction()
    {
        $percontypemodel = new Default_Model_periodcontroltype();
        $call = $this->_getParam('call');
        if ($call == 'ajaxcall') {
            $this->_helper->layout->disableLayout();
        }
        $dashboardcall = $this->_getParam('dashboardcall');
        $refresh = $this->_getParam('refresh');
        $data = array();

        if ($refresh == 'refresh') {
            if ($dashboardcall == 'Yes') {
                $perPage = DASHBOARD_PERPAGE;
            } else {
                $perPage = PERPAGE;
            }
            $sort = 'DESC';
            $by = 'control_type';
            $pageNo = 1;
            $searchData = '';
        } else {
            $sort = ($this->_getParam('sort') != '') ? $this->_getParam('sort') : 'DESC';
            $by = ($this->_getParam('by') != '') ? $this->_getParam('by') : 'control_type';
            if ($dashboardcall == 'Yes') {
                $perPage = $this->_getParam('per_page', DASHBOARD_PERPAGE);
            } else {
                $perPage = $this->_getParam('per_page', PERPAGE);
            }
            $pageNo = $this->_getParam('page', 1);
            $searchData = $this->_getParam('searchData');
            $searchData = rtrim($searchData, ',');
        }

        $dataTmp = $percontypemodel->getGrid($sort, $by, $perPage, $pageNo, $searchData, $call, $dashboardcall);

        array_push($data, $dataTmp);

        $this->view->dataArray = $data;

        $this->view->call = $call;
		$this->view->messages = $this->_helper->flashMessenger->getMessages();
    }

    public function editAction()
    {
        $perconform = new Default_Form_periodcontroltype();
        $percontypemodel = new Default_Model_periodcontroltype();
        $periods = $percontypemodel->getPeriod();
        foreach ($periods as $key => $period) {
            $perconform->period->addMultiOption($period['period_id'], $period['name']);
        }

            $perconform->setAttrib('action', BASE_URL . 'periodcontroltype/edit/id/' . $this->_request->getParam('id'));
            $periodcontrol = $percontypemodel->getPeriodControlTypeByid($this->_request->getParam('id'));
            $perconform->period->setValue($periodcontrol['period_id']);
            $perconform->controltype->setValue($periodcontrol['control_type']);
            $perconform->isauto->setValue(utlis::getcheckboxvalue($periodcontrol['isautogenerated'], 'form'));
        

        if ($this->getRequest()->isPost()) {
            $auth = Zend_Auth::getInstance();
            if ($auth->hasIdentity()) {
                $loginid = $auth->getStorage()->read()->id;
            }
            try {
                    if ($perconform->isValid($this->getRequest()->getPost())) {
                        $period = $this->_request->getParam('period');
                        $controltype  = $this->_request->getParam('controltype');
                        $isgautogen = $this->_request->getParam('isauto');

                        $percondata = array(
                            'period_id' => $period,
                            'control_type' => $controltype,
                            'modifiedby' => $loginid,
                            'modifieddate' => gmdate("Y-m-d H:i:s"),
                            'isautogenerated' => utlis::getcheckboxvalue($isgautogen)
                        );

                            $menuID = PERIODCONTROL;
                          
                           $Id=$percontypemodel->savaorupdateperiodcontrol($percondata, 'periodcontrol_id = ' . $this->_request->getParam('id'));
                            if($Id == 'update')
                            {
                                $tableid = $this->_request->getParam('id'); 
                                                          
                                  $this->_helper->getHelper("FlashMessenger")->addMessage(array("success"=>"Period Control updated successfully."));
                            }
                            else
                            {
                                $tableid = $Id;
                                $this->_helper->getHelper("FlashMessenger")->addMessage(array("success"=>"Period Control  added successfully."));
                            }
                            sapp_Global::logManager($menuID,$this->actionupdate,$loginid,$tableid);

                    $this->_redirect('/periodcontroltype');
                }
                $messages = $perconform->getMessages();

                foreach ($messages as $key1 => $value) {
                    foreach ($value as $key2 => $value2) {
                        $msgArray[$key1] = $value2;
                        break;
                    }
                }
            } catch (\Throwable $th) {
                Zend_Debug::dump($th->getMessage());
            }
        }
        $this->view->msgarray = $msgArray;
        $this->view->form = $perconform;
    }

